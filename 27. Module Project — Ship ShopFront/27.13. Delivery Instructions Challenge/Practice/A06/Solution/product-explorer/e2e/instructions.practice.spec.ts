import { expect, test } from "@playwright/test";
test("saved delivery instructions appear after a history reload", async ({ page }) => {
 await page.goto("/products/p1");
 await page.getByRole("button", { name: "Add to bag", exact: true }).click();
 await page.getByRole("link", { name: "Your bag 1", exact: true }).click();
 await page.getByRole("link", { name: "Review checkout", exact: true }).click();
 await expect(page).toHaveURL(/\/login\?returnTo=%2Fcheckout$/);
 await page.getByRole("textbox", { name: "Email address", exact: true }).fill("jordan@example.com");
 await page.getByLabel("Password", { exact: true }).fill("PracticeOnly42!");
 await page.getByRole("button", { name: "Sign in", exact: true }).click();
 await expect(page).toHaveURL(/\/checkout$/);
 await page.getByRole("textbox", { name: "Full name" }).fill("Alex Morgan");
 await page.getByRole("textbox", { name: "Email address", exact: true }).fill("alex@example.com");
 await page.getByRole("textbox", { name: "Street address", exact: true }).fill("14 Lake Road");
 await page.getByRole("textbox", { name: "City", exact: true }).fill("Riverton");
 await page.getByRole("textbox", { name: "ZIP code", exact: true }).fill("12345");
 await page.getByRole("textbox", { name: "Delivery instructions, optional", exact: true }).fill("Leave at reception");
 await page.getByRole("combobox", { name: "Delivery method" }).selectOption("pickup");
 await expect(page.getByRole("textbox", { name: "Delivery instructions, optional", exact: true })).toHaveCount(0);
 await page.getByRole("combobox", { name: "Delivery method" }).selectOption("standard");
 await expect(page.getByRole("textbox", { name: "Delivery instructions, optional", exact: true })).toHaveValue("Leave at reception");
 await page.getByRole("button", { name: "Place practice order", exact: true }).click();
 await expect(page.getByRole("heading", { name: "Your practice order is confirmed.", exact: true })).toBeVisible();
 await expect(page.getByText("Delivery instructions: Leave at reception", { exact: true })).toBeVisible();
 await page.getByRole("link", { name: "View my orders", exact: true }).click();
 await expect(page).toHaveURL(/\/orders$/);
 await expect(page.getByRole("heading", { name: "Your orders.", exact: true })).toBeVisible();
 await page.reload();
 await expect(page.getByRole("heading", { name: "Your orders.", exact: true })).toBeVisible();
 await expect(page.getByText("Delivery instructions: Leave at reception", { exact: true }).first()).toBeVisible();
});
