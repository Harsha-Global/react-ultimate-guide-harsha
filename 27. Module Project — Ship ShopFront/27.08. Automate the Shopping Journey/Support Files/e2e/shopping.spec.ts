import { expect, test } from "@playwright/test";
test("a new visitor signs in, collects a practice order and reloads its history", async ({ page }) => {
  await page.goto("/products/p1");
  await page.getByRole("button", { name: "Add to bag", exact: true }).click();
  await page.getByRole("link", { name: "Your bag 1", exact: true }).click();
  await page.getByRole("link", { name: "Review checkout", exact: true }).click();
  await expect(page).toHaveURL(/\/login\?returnTo=%2Fcheckout$/);
  await page.getByRole("textbox", { name: "Email address", exact: true }).fill("jordan@example.com");
  await page.getByLabel("Password", { exact: true }).fill("PracticeOnly42!");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/\/checkout$/);
  await page.getByRole("textbox", { name: "Full name", exact: true }).fill("Alex Morgan");
  await page.getByRole("textbox", { name: "Email address", exact: true }).fill("alex@example.com");
  await page.getByRole("combobox", { name: "Delivery method" }).selectOption("pickup");
  await page.getByRole("button", { name: "Place practice order" }).click();
  await expect(page.getByText("Choose a collection window.", { exact: true })).toBeVisible();
  await page.getByRole("combobox", { name: "Collection window" }).selectOption("morning");
  await page.getByRole("button", { name: "Place practice order" }).click();
  await expect(page.getByRole("heading", { name: "Your practice order is confirmed." })).toBeVisible();
  await expect(page.getByText("Studio pickup · 10 am–12 pm", { exact: true })).toBeVisible();
  await expect(page.getByRole("link", { name: "Your bag 0", exact: true })).toBeVisible();
  await page.getByRole("link", { name: "View my orders", exact: true }).click();
  await expect(page).toHaveURL(/\/orders$/);
  await expect(page.getByRole("heading", { name: "Your orders.", exact: true })).toBeVisible();
  await expect(page.getByText("Studio pickup · 10 am–12 pm", { exact: true }).first()).toBeVisible();
  await page.reload();
  await expect(page.getByRole("heading", { name: "Your orders.", exact: true })).toBeVisible();
  await expect(page.getByText("Studio pickup · 10 am–12 pm", { exact: true }).first()).toBeVisible();
});
test("switching back to delivery retains the entered address", async ({ page }) => {
  await page.goto("/login?returnTo=%2Fcheckout");
  await page.getByRole("textbox", { name: "Email address", exact: true }).fill("jordan@example.com");
  await page.getByLabel("Password", { exact: true }).fill("PracticeOnly42!");
  await page.getByRole("button", { name: "Sign in", exact: true }).click();
  await expect(page).toHaveURL(/\/checkout$/);
  await page.getByRole("textbox", { name: "Street address", exact: true }).fill("14 Lake Road");
  await page.getByRole("combobox", { name: "Delivery method" }).selectOption("pickup");
  await expect(page.getByRole("textbox", { name: "Street address", exact: true })).toHaveCount(0);
  await page.getByRole("combobox", { name: "Delivery method" }).selectOption("standard");
  await expect(page.getByRole("textbox", { name: "Street address", exact: true })).toHaveValue("14 Lake Road");
});
